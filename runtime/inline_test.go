func TestInline(t *testing.T) {
	m, err := Compile(inlineWasm)
	if err != nil {
		t.Fatal(err)
	}
	c := m.Compiled()
	for _, i := range []int{4, 5, 6, 7, 8} {
		if fn := c.Funcs[i]; len(fn.Inlined) == 0 || fn.Plain == nil {
			t.Fatalf("func[%d] inlined nothing", i)
		}
	}

	for _, hooked := range []bool{false, true} {
		s := NewStore()
		enters := 0
		if hooked {
			s.SetHooks(&Hooks{Enter: func(*Function, []uint64) { enters++ }})
		}
		inst, err := s.Instantiate(m, nil)
		if err != nil {
			t.Fatal(err)
		}
		call := func(name string, arg uint64) uint64 {
			t.Helper()
			res, err := inst.Func(name).Call(arg)
			if err != nil {
				t.Fatalf("%s(%d): %v", name, arg, err)
			}
			return res[0]
		}
		if got := call("peek", 0); got != 42 {
			t.Errorf("hooks=%v: peek(0) = %d, want 42", hooked, got)
		}
		if got := call("inc", 5); got != 11 {
			t.Errorf("hooks=%v: inc(5) = %d, want 11", hooked, got)
		}
		enters = 0
		if got := call("loop", 4); got != 42 {
			t.Errorf("hooks=%v: loop(4) = %d, want 42", hooked, got)
		}
		// With hooks, inlined calls still enter: loop, then pick and sub
		// four times each.
		if hooked && enters != 9 {
			t.Errorf("loop(4) entered %d functions, want 9", enters)
		}

		// A trap inside an inlined body shows the callee's frame.
		_, err = inst.Func("peek").Call(65532)
		var trap *Trap
		if !errors.As(err, &trap) || trap.Code != TrapMemoryOutOfBounds {
			t.Fatalf("hooks=%v: got %v, want out of bounds", hooked, err)
		}
		if len(trap.Stack) != 2 || trap.Stack[0].Func.Index() != 0 || trap.Stack[1].Func.Name() != "peek" {
			t.Fatalf("hooks=%v: trap stack %v", hooked, trap)
		}
		if pc := trap.Stack[0].PC; c.Funcs[0].Code[pc].Op.String() != "load32" {
			t.Errorf("hooks=%v: trap at callee pc %d, want the load", hooked, pc)
		}

		// peek2 inlines $load2, which inlined $load.
		if got := call("peek2", 0); got != 42 {
			t.Errorf("hooks=%v: peek2(0) = %d, want 42", hooked, got)
		}
		_, err = inst.Func("peek2").Call(65530)
		if !errors.As(err, &trap) || trap.Code != TrapMemoryOutOfBounds {
			t.Fatalf("hooks=%v: got %v, want out of bounds", hooked, err)
		}
		if len(trap.Stack) != 3 || trap.Stack[0].Func.Index() != 0 || trap.Stack[1].Func.Index() != 7 ||
			trap.Stack[2].Func.Name() != "peek2" {
			t.Fatalf("hooks=%v: trap stack %v", hooked, trap)
		}
	}
}
