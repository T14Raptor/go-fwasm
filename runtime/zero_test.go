func TestZeroLocals(t *testing.T) {
	m, err := Compile(zeroWasm)
	if err != nil {
		t.Fatal(err)
	}
	c := m.Compiled()
	if f := c.Funcs[1]; f.ZeroFrom != 1 || f.ZeroTo != 2 {
		t.Errorf("$cond zeroes [%d, %d), want [1, 2)", f.ZeroFrom, f.ZeroTo)
	}
	if f := c.Funcs[2]; f.ZeroFrom != f.ZeroTo {
		t.Errorf("$always zeroes [%d, %d), want nothing", f.ZeroFrom, f.ZeroTo)
	}
	// Without hooks the calls are inlined; with them they are real calls.
	for _, hooks := range []*Hooks{nil, {}} {
		s := NewStore()
		s.SetHooks(hooks)
		inst, err := s.Instantiate(m, nil)
		if err != nil {
			t.Fatal(err)
		}
		for arg, want := range []uint64{1, 7} {
			res, err := inst.Func("run").Call(uint64(arg))
			if err != nil || res[0] != want {
				t.Errorf("hooks=%v: run(%d) = %v, %v; want %d", hooks != nil, arg, res, err, want)
			}
		}
	}
}
